#!/usr/bin/env python3
"""Emit optional Jog helpers that copy mesh SPIR-V into a destination buffer.

Prefer runtime load via tex_load_file from examples/dust2_fps/assets/*.spv.
This script is a fallback when an embed is required.

Usage:
  python3 embed_spv.py
  python3 embed_spv.py --out ../../shaders_spv.jog
"""

from __future__ import annotations

import argparse
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT_OUT = HERE / "shaders_spv.jog"
VERT = HERE / "mesh.vert.spv"
FRAG = HERE / "mesh.frag.spv"
CHUNK = 32


def _emit_copy_fn(name: str, data: bytes) -> str:
    lines = [
        f"fn {name}(dst: *byte) {{",
        f"    // {len(data)} bytes",
    ]
    for i in range(0, len(data), CHUNK):
        chunk = data[i : i + CHUNK]
        assigns = " ".join(f"dst[{i + j}] = {b}" for j, b in enumerate(chunk))
        lines.append(f"    {assigns}")
    lines.append("}")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--vert", type=Path, default=VERT)
    ap.add_argument("--frag", type=Path, default=FRAG)
    args = ap.parse_args()

    vert = args.vert.read_bytes()
    frag = args.frag.read_bytes()
    if len(vert) < 4 or vert[:4] != b"\x03\x02\x23\x07":
        raise SystemExit(f"not SPIR-V: {args.vert}")
    if len(frag) < 4 or frag[:4] != b"\x03\x02\x23\x07":
        raise SystemExit(f"not SPIR-V: {args.frag}")

    body = "\n".join(
        [
            "// AUTO-GENERATED by engine/render3d/shaders/embed_spv.py — do not edit.",
            "// Prefer loading mesh.vert.spv / mesh.frag.spv from assets/ at runtime.",
            f"val R3D_VERT_SPV_LEN: i64 = {len(vert)}",
            f"val R3D_FRAG_SPV_LEN: i64 = {len(frag)}",
            "",
            _emit_copy_fn("r3d_copy_vert_spv", vert),
            "",
            _emit_copy_fn("r3d_copy_frag_spv", frag),
            "",
            "fn r3d_vert_spv_bytes(): *byte {",
            "    val p = alloc(R3D_VERT_SPV_LEN)",
            "    r3d_copy_vert_spv(p)",
            "    return p",
            "}",
            "",
            "fn r3d_frag_spv_bytes(): *byte {",
            "    val p = alloc(R3D_FRAG_SPV_LEN)",
            "    r3d_copy_frag_spv(p)",
            "    return p",
            "}",
            "",
        ]
    )
    args.out.write_text(body)
    print(f"wrote {args.out} vert={len(vert)} frag={len(frag)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
